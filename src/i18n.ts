export type MessageKey = keyof typeof RUSSIAN;
export function translate(language: Language, key: MessageKey): string { return language === 'ru' ? RUSSIAN[key] : key; }

export function loadLanguage(storage?: StorageLike): Language {
  try { return (storage ?? sessionStorage).getItem(LANGUAGE_KEY) === 'ru' ? 'ru' : 'en'; }
  catch { return 'en'; }
}
export function saveLanguage(language: Language, storage?: StorageLike): void {
  try { (storage ?? sessionStorage).setItem(LANGUAGE_KEY, language); }
  catch { /* Language selection remains usable without storage. */ }
}

function pluralRu(count: number, forms: readonly [string, string, string]): string {
  const lastTwo = count % 100;
  return forms[lastTwo >= 11 && lastTwo <= 14 ? 2 : count % 10 === 1 ? 0 : count % 10 >= 2 && count % 10 <= 4 ? 1 : 2];
}

export function labels(language: Language) {
  const t = (key: MessageKey) => translate(language, key);
  return {
    type: (type: GuessType) => language === 'ru' && type === 'minor7Interval' ? 'Малая септима' : language === 'ru' && type === 'major7Interval' ? 'Большая септима' : t(DEFINITIONS[type].label),
    group: (group: typeof INTERVALS[keyof typeof INTERVALS]['group']) => t(group),
    intervalGroup: (group: typeof INTERVALS[keyof typeof INTERVALS]['group']) => language === 'ru' ? `Интервалы: ${t(group)}` : `${group} intervals`,
    guess: (name: string) => language === 'ru' ? `Ответ: ${name}` : `Guess ${name}`,
    round: (round: number) => `${language === 'ru' ? 'РАУНД' : 'ROUND'} ${String(round).padStart(2, '0')}`,
    selected: (count: number) => language === 'ru' ? `${count} ${pluralRu(count, ['нота выбрана', 'ноты выбраны', 'нот выбрано'])}` : `${count} ${count === 1 ? 'note' : 'notes'} selected`,
    found: (count: number, intervals: boolean) => language === 'ru' ? `${pluralRu(count, ['Угадан', 'Угадано', 'Угадано'])} ${count} ${pluralRu(count, intervals ? ['интервал', 'интервала', 'интервалов'] : ['аккорд', 'аккорда', 'аккордов'])}` : `${count} ${intervals ? 'intervals' : 'chords'} found`,
    celebrationFound: (count: number, intervals: boolean) => language === 'ru' ? `${pluralRu(count, ['УГАДАН', 'УГАДАНО', 'УГАДАНО'])} ${count} ${pluralRu(count, intervals ? ['ИНТЕРВАЛ', 'ИНТЕРВАЛА', 'ИНТЕРВАЛОВ'] : ['АККОРД', 'АККОРДА', 'АККОРДОВ'])}` : `${count} ${intervals ? 'INTERVALS' : 'CHORDS'} FOUND`,
    explored: (count: number, total: number) => language === 'ru' ? `${count} / ${total} угадано дважды` : `${count} / ${total} explored twice`,
    correct: (count: number) => language === 'ru' ? `Правильных ответов: ${count}` : `${count} correct`,
    octave: (octave: number) => `${t('Octave')} ${octave}`,
    note: (note: number) => language === 'en' ? noteLabel(note) : `${['До', 'До-диез / Ре-бемоль', 'Ре', 'Ре-диез / Ми-бемоль', 'Ми', 'Фа', 'Фа-диез / Соль-бемоль', 'Соль', 'Соль-диез / Ля-бемоль', 'Ля', 'Ля-диез / Си-бемоль', 'Си'][note % 12]}${Math.floor(note / 12) - 1}`,
  };
}
